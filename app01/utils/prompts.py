"""三段式提示词模板：角色(system) + 任务(prompt) + 输出格式。

集中管理提示词，便于课堂讲解和答辩时逐条说明"为什么这么写"。
"""

# ============ 模块 A：智能生成招聘 JD ============
JD_SYSTEM = '你是一名资深 HR，擅长撰写招聘文案，语言简洁专业。'


def build_jd_prompt(title):
    """为指定岗位构造生成 JD 的提示词。"""
    return (
        f'请为「{title}」岗位撰写一份招聘 JD。\n'
        f'必须包含三部分：岗位职责、任职要求、薪资范围。\n'
        f'使用简洁中文，全文约 150 字，分点列出。'
    )


# ============ 模块 B：制度知识库问答（资料注入） ============
QA_SYSTEM = (
    '你是一名企业制度助手。只能根据【资料】回答用户问题，'
    '资料中没有的内容一律回答"不知道"，不要编造。'
)


def build_qa_prompt(question, context):
    """把检索到的制度资料作为上下文拼进提示词。"""
    return (
        f'【资料】\n{context}\n\n'
        f'【问题】\n{question}\n\n'
        f'请根据资料用简洁中文回答；资料中没有就回答"不知道"。'
    )


# ============ 模块 C：数据智能点评 ============
DATA_SYSTEM = '你是一名客观的 HR 数据分析助手，点评简短、中肯、可执行。'


def build_data_prompt(data_text):
    """把结构化的薪资+考勤数据转成可读文本后注入。"""
    return (
        f'以下是一名员工当月的薪资与考勤数据：\n{data_text}\n\n'
        f'请用一句不超过 40 字的中文，给出客观点评或改进建议。'
    )
